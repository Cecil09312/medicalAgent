#!/bin/bash
# ============================================================
# AI智能医疗诊断系统 - 容器启动入口
# 职责：
#   1. 加载环境变量
#   2. 检测知识库是否已初始化，未初始化则自动导入文档
#   3. 启动 Web 服务
# ============================================================
set -e

echo "=========================================================="
echo "  AI智能医疗诊断系统 - 容器启动"
echo "=========================================================="

cd /app

# ------------------------------------------------------------
# 1. 环境变量检查
# ------------------------------------------------------------
if [ -f /app/.env ]; then
    echo "[INFO] 检测到 .env 文件"
    set -a
    source /app/.env
    set +a
else
    echo "[WARN] 未检测到 .env 文件，请确保已通过 docker-compose 的 environment/env_file 传入 LLM_API_KEY 等配置"
fi

if [ -z "${LLM_API_KEY}" ]; then
    echo "[WARN] LLM_API_KEY 未设置，对话功能将不可用"
fi

# ------------------------------------------------------------
# 2. 初始化知识库
#    Milvus Lite 数据库为文件锁（单进程），知识库未存在时才导入，
#    避免容器重启重复导入造成 doc_id 冲突。
# ------------------------------------------------------------
KB_DB_DIR="/app/knowledge/data/milvus_lite.db"

if [ ! -d "${KB_DB_DIR}" ]; then
    echo "[INFO] 知识库未初始化，开始导入文档（首次启动，耗时约 1-2 分钟）..."
    python -m knowledge.scripts.import_hardcoded_data
    echo "[INFO] 知识库初始化完成"
else
    echo "[INFO] 知识库已存在，跳过初始化"
fi

# ------------------------------------------------------------
# 3. 启动 Web 服务
# ------------------------------------------------------------
echo "[INFO] 启动 Web 服务，监听端口 7860"
echo "[INFO] 访问地址: http://localhost:7860"
echo "=========================================================="

exec python main.py
